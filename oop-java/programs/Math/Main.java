public class Main {
   public static void main(String[] args) {

      System.out.println("Square root of 25: " + Math.sqrt(25));
      System.out.println("Power (2^3): " + Math.pow(2, 3));
      System.out.println("Maximum of 10 and 20: " + Math.max(10, 20));
      System.out.println("Minimum of 10 and 20: " + Math.min(10, 20));
      System.out.println("Absolute value of -15: " + Math.abs(-15));
      System.out.println("Random number: " + Math.random());
      System.out.println("Ceiling of 5.4: " + Math.ceil(5.4));
      System.out.println("Floor of 5.9: " + Math.floor(5.9));
      System.out.println("Round of 5.6: " + Math.round(5.6));
   }
}