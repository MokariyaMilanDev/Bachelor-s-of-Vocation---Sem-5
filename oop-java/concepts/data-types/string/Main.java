
public class Main {
   public static void main(String[] args) {
      String string = "This is String";
      System.out.println(string);
      System.out.println(string.length());
      System.out.println(string.concat(string));
      System.out.println(string.equals(string));
      System.out.println(string.compareTo(string));
      System.out.println(string.compareToIgnoreCase(string));
      System.out.println(string.indexOf("String"));
      System.out.println(string.charAt(5));
      System.out.println(string.substring(0));
      System.out.println(string.toUpperCase());
      System.out.println(string.toLowerCase());
   }
}
